        M.add("rFamEqOnlyFOne", only1, "measured", "tasks with a phantom in F1 only")
        M.add("rFamEqOnlyFTwo", only2, "measured", "tasks with a phantom in F2 only")
        M.add("rFamEqMcNemarP", f"$p={pmc:.2f}$" if pmc >= 0.01 else "$p<0.01$", "computed", "exact McNemar test, two-sided")
        for f, nm in (("F1", "FOne"), ("F2", "FTwo")):
            gf = [g for g in fq0 if g["family"] == f]
            M.add(f"rFamEq{nm}Gen", len(gf), "measured", f"famcmp {f} answers")
            M.add(f"rFamEq{nm}Trunc", sum(1 for g in gf if g.get("finish_reason") == "length"), "measured",
                  f"famcmp {f} answers at the token limit")
            M.add(f"rFamEq{nm}Decl", pct(fe[f]["decl"]["p"]), "computed", f"famcmp {f} declaration rate")
