    # ---------------- prevalence -----------------------------------------
    def prevalence(filter_resp=lambda r: True, filter_dep=lambda d: True, rb=None, db=None):
        """Declaration- and response-level phantom rates.  Intervals: percentile bootstrap
        over tasks (all responses to one task, across models and families, form a cluster)."""
        rb = resp_by_key if rb is None else rb
        db = deps_by_resp if db is None else db
        decl_c, resp_c = collections.defaultdict(lambda: [0, 0]), collections.defaultdict(lambda: [0, 0])
        for k, r in rb.items():
            if not filter_resp(r):
                continue
            ds = [d for d in db.get(k, []) if d["cls"] in ("exists", "phantom") and filter_dep(d)]
            if not ds:
                continue
            ph = sum(1 for d in ds if d["cls"] == "phantom")
            t = r["task_id"]
            decl_c[t][0] += ph
            decl_c[t][1] += len(ds)
            resp_c[t][0] += 1 if ph else 0
            resp_c[t][1] += 1
        k = sum(c[0] for c in decl_c.values())
        n = sum(c[1] for c in decl_c.values())
        rk = sum(c[0] for c in resp_c.values())
        rn = sum(c[1] for c in resp_c.values())
        nan3 = (float("nan"),) * 3
        p, lo, hi = cluster_bootstrap([tuple(c) for c in decl_c.values()]) if n else nan3
        rp, rlo, rhi = cluster_bootstrap([tuple(c) for c in resp_c.values()]) if rn else nan3
        return {"decl": {"k": k, "n": n, "p": p, "lo": lo, "hi": hi, "clusters": len(decl_c)},
                "resp": {"k": rk, "n": rn, "p": rp, "lo": rlo, "hi": rhi, "clusters": len(resp_c)}}

    prev = {"overall": prevalence()}
