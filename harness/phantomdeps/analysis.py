def phantom_key(d) -> tuple:
    """A phantom as the installer resolves it: ecosystem, owner (PlatformIO, ESP; the pseudonymised
    files keep its place) and the name as the registry compares names.  The persistence pass counts a
    resample as repeating a phantom only if it names the same owner too."""
    return (d["eco"], (d.get("owner") or "").lower(), reg_norm(d["eco"], d["name"]))


def mcnemar_exact(only1: int, only2: int) -> float:
    """Two-sided exact McNemar test on the discordant pairs."""
    nd = only1 + only2
    return min(1.0, 2 * sum(math.comb(nd, i) for i in range(0, min(only1, only2) + 1)) / 2 ** nd) if nd else 1.0


def check_harness(metas) -> None:
    """Results must come from the shipped code and snapshots: the classification of every
    run has to be produced by the current harness and derived files."""
    from .classify import derived_hash, harness_hash
    cur_h, cur_d = harness_hash(), derived_hash()
    for m in metas:
        c = m["classify"]
        if c.get("harness_sha256") != cur_h or c.get("derived_sha256") != cur_d:
            raise AssertionError(f"run {c.get('run_id')} was classified with other code or snapshots; "
                                 "re-run `phantomdeps classify` before `analyze`")


def check_text_assumptions(prof) -> None:
    """Section VI states consequences of the assigned profile; stop if they no longer hold."""
    a, th = prof.alpha, prof.theta
    one = 1 - a["prov"]                       # resolved, established, pinned, no provenance
    assert one >= th, "text: a single pinned, established dependency is admitted"
    assert one * one < th, "text: two such dependencies fall below theta"
    assert a["res"] + a["est"] < th, "text: an unpinned established dependency falls below theta"
    assert a["res"] + a["pin"] < th and a["res"] < th, "text: the index-only rule admits no squat"
    assert 1 - a["res"] < th, "text: a phantom caps the upper index of the index-only rule below theta"


