def _dot(ax, v, y, color, marker):
    """A rate with its interval; cells with fewer than MIN_DECL declarations or without an
    interval (a single task) get a hollow marker and no bar: they are not interpreted."""
    x = 100 * v["p"]
    thin = v["n"] < MIN_DECL or v["lo"] != v["lo"]
    if not thin:
        ax.errorbar([x], [y], xerr=[[x - 100 * v["lo"]], [100 * v["hi"] - x]], fmt=marker, ms=4, color=color,
                    ecolor=color, elinewidth=1.0, capsize=0, mec="white", mew=0.6)
    else:
        ax.plot([x], [y], marker, ms=4, color=color, mfc="white", mec=color, mew=1.0)


