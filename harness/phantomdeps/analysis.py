    prev["by_task_eco"] = {e: prevalence(lambda r, e=e: r["eco"] == e) for e in ECO_ORDER}
    prev["by_model_eco"] = {m: {e: prevalence(lambda r, m=m: r["model_id"] == m, lambda d, e=e: d["eco"] == e)
                                for e in ECO_ORDER} for m in model_ids}
    prev["by_tier"] = {t: prevalence(lambda r, t=t: r["tier"] == t) for t in ("common", "niche")}
    prev["by_family"] = {f: prevalence(lambda r, f=f: r["family"] == f) for f in fams}
