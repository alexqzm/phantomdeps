def pct(p, digits=1):
    if p != p:  # NaN
        return "n/a"
    return f"{100 * p:.{digits}f}\\%"


def pct0(p):
    """A whole percentage, but never 100% or 0% for a share that is not exactly one or zero."""
    if p != p:
        return "n/a"
    s = pct(p, 0)
    return pct(p, 1) if (s == "100\\%" and p < 1) or (s == "0\\%" and p > 0) else s


def ci(lo, hi, digits=1):
    if lo != lo:
        return "n/a"
    return f"[{100 * lo:.{digits}f}, {100 * hi:.{digits}f}]"


def ci_cell(v, digits=1):
    """Interval for a table cell: none for empty cells or a single task."""
    return ci(v["lo"], v["hi"], digits) if v["n"] and v["lo"] == v["lo"] else "--"


def tex_escape(s: str) -> str:
    rep = {"\\": "\\textbackslash{}", "&": "\\&", "%": "\\%", "$": "\\$", "#": "\\#", "_": "\\_",
           "{": "\\{", "}": "\\}", "~": "\\textasciitilde{}", "^": "\\textasciicircum{}"}
    return "".join(rep.get(c, c) for c in s)


class Macros:
    """Collect \\newcommand macros with provenance; names must be letters only."""

    def __init__(self):
        self.items: dict[str, dict] = {}

    def add(self, name: str, value, prov: str, key: str = ""):
        assert name.isalpha(), name
        self.items[name] = {"value": str(value), "prov": prov, "key": key}

    def write(self, path: Path):
        lines = ["% generated by phantomdeps.analysis -- do not edit", f"% {utcnow()}"]
        for n, v in sorted(self.items.items()):
            lines.append(f"\\newcommand{{\\{n}}}{{{v['value']}}} % {v['prov']} {v['key']}")
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


