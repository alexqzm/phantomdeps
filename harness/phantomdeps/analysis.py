def short_model(mid: str) -> str:
    return SHORT.get(mid, mid)


def _prevalence_by_model_rows(R, out_dir: Path, model_ids):
    """Study layout (many models): one row per model, one column per ecosystem."""
    prev = R["prevalence"]
    ecos = [e for e in ECO_ORDER if prev["by_eco"][e]["decl"]["n"]]
    lines = ["\\begin{tabular}{@{}l" + "r" * (len(ecos) + 2) + "@{}}", "\\toprule",
             "Model & " + " & ".join(ECO_LABEL[e] for e in ecos) + " & All & Responses \\\\", "\\midrule"]
    for m in model_ids:
        cells = []
        for e in ecos:
            v = prev["by_model_eco"][m][e]["decl"]
            cells.append(f"{v['k']}/{v['n']}" if v["n"] else "--")
        a, r = prev["by_model"][m]["decl"], prev["by_model"][m]["resp"]
        lines.append(f"{tex_escape(short_model(m))} & " + " & ".join(cells) +
                     f" & {pct(a['p'])} & {pct(r['p'])} \\\\")
    lines.append("\\midrule")
    cells = []
    for e in ecos:
        a = prev["by_eco"][e]["decl"]
        cells.append(f"{a['k']}/{a['n']}")
    o, r = prev["overall"]["decl"], prev["overall"]["resp"]
    lines.append("All & " + " & ".join(cells) + f" & {pct(o['p'])} & {pct(r['p'])} \\\\")
    lines.append("Rate & " + " & ".join(pct(prev["by_eco"][e]["decl"]["p"]) for e in ecos) + " & & \\\\")

    def ci_cell(v):  # task-cluster bootstrap interval in whole percent; none from a single task
        if v["n"] == 0 or v.get("clusters", 0) < 2 or v["lo"] != v["lo"]:
            return "--"
        return f"[{100 * v['lo']:.0f}, {100 * v['hi']:.0f}]"
    lines.append("95\\% CI & " + " & ".join(ci_cell(prev["by_eco"][e]["decl"]) for e in ecos) + " & & \\\\")
    lines.append("Responses & " + " & ".join(pct(prev["by_eco"][e]["resp"]["p"], 0) for e in ecos) + " & & \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out_dir / "tab_prevalence.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


