        M.add("rFamBoth", fc["paired"]["both"], "measured", "pairs with a phantom in both answers")
        M.add("rFamMcNemarP", f"$p={pmc:.2f}$" if pmc >= 0.01 else ("$p<0.001$" if pmc < 0.001 else "$p<0.01$"),
              "computed", "exact McNemar test over (model, task) pairs, two-sided")
        for f, nm in (("F1", "FOne"), ("F2", "FTwo")):
            gf = [g for g in gens0 if g["family"] == f and g["model_id"] in cmp_models and not g.get("error")]
